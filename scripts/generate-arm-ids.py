#!/usr/bin/env python3
"""Generate the native ARM ID registry from bundled, pinned upstream sources.

The inputs are included so source distributions can reproduce the generated Go
without network access. util-linux data is GPL-2.0-or-later. Fastfetch additions
and display spellings are MIT; the combined generated table retains both.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
SOURCES = {
    'lscpu-arm.c': '9286505dc43d50acecfaec26c21b62746b6a9f4cf9de1a8797ff2fa800e3ee18',
    'fastfetch_cpu_arm.h': '771487aac6311c9cef0b845c39833252674bfdafee0e0cb2f1e9187a63e8eac5',
}


def source(name):
    data = (ROOT / 'internal/CLI/data' / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCES[name]:
        raise SystemExit(f'pinned ARM source changed: {name}')
    return data.decode()


def registry():
    util = source('lscpu-arm.c')
    fast = source('fastfetch_cpu_arm.h')
    tables = {}
    for name, body in re.findall(r'static const struct id_part (\w+)\[\] = \{(.*?)\n\};', util, re.S):
        tables[name] = {int(n, 16): label for n, label in re.findall(r'\{\s*(0x[0-9a-f]+),\s*"([^"]+)"', body)}
    impl_body = re.search(r'static const struct hw_impl hw_implementer\[\] = \{(.*?)\n\};', util, re.S)
    if impl_body is None:
        raise SystemExit('cannot find util-linux implementers')
    vendors, parts = {}, {}
    fast_vendors = dict((int(n, 16), label) for n, label in re.findall(r'case (0x[0-9a-fA-F]+):\s*return "([^"]+)";', fast.split('static const char* armPartId2name', 1)[0]))
    for number, table, vendor in re.findall(r'\{\s*(0x[0-9a-f]+),\s*(\w+),\s*"([^"]+)"', impl_body.group(1)):
        impl = int(number, 16)
        vendors[impl] = fast_vendors.get(impl, vendor)
        entries = dict(tables[table])
        prefix = table.removesuffix('_part')
        body = re.search(r'static const char\* ' + re.escape(prefix) + r'PartId2name\(.*?\n\}', fast, re.S)
        if body:
            entries.update({int(n, 16): label for n, label in re.findall(r'case (0x[0-9a-fA-F]+):\s*return "([^"]+)";', body.group())})
        if entries:
            parts[impl] = entries
    if len(vendors) != 19 or sum(map(len, parts.values())) != 212:
        raise SystemExit(f'unexpected ARM source structure or coverage: {len(vendors)} vendors, {sum(map(len, parts.values()))} parts')
    return vendors, parts


def render():
    vendors, parts = registry()
    lines = [
        '// Code generated by scripts/generate-arm-ids.py; DO NOT EDIT.',
        '// SPDX-License-Identifier: GPL-2.0-or-later AND MIT',
        '// Copyright (C) 2018 Riku Voipio <riku.voipio@iki.fi>',
        '// Copyright (c) 2021-2023 Linus Dierheimer',
        '// Copyright (c) 2022-2026 Carter Li',
        '// Copyright (c) 2026 ffgan (Go conversion)',
        '// Inputs, revisions and notices: data/README and docs/provenance.md.',
        '', 'package cli', '', 'var armVendors = map[uint32]string{',
    ]
    lines.extend(f'0x{k:x}: {json.dumps(v)},' for k, v in sorted(vendors.items()))
    lines.extend(['}', '', 'var armParts = map[uint32]map[uint32]string{'])
    for impl, entries in sorted(parts.items()):
        lines.append(f'0x{impl:x}: {{')
        lines.extend(f'0x{k:x}: {json.dumps(v)},' for k, v in sorted(entries.items()))
        lines.append('},')
    lines.append('}')
    # gofmt is part of the required Go toolchain; it makes output independent of
    # handwritten alignment and stable across Python versions.
    result = subprocess.run(['gofmt'], input='\n'.join(lines)+'\n', text=True, capture_output=True, check=True)
    return result.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'internal/CLI/armids_data.go'
    generated = render()
    if args.check:
        if target.read_text() != generated:
            raise SystemExit('generated ARM registry differs; run scripts/generate-arm-ids.py')
        print('Pinned ARM inputs and generated registry verified')
    else:
        target.write_text(generated)


if __name__ == '__main__':
    main()
